// DESIGN.md report index: a sticky line of text that knows where you are.
function ReportIndex({ ledger }: { ledger?: SalvageLedger }) {
  const sections = SECTIONS.filter((s) => {
    if (s.id === 'ceiling') return Boolean(ledger?.exit);
    if (s.id === 'sensitivity') return Boolean(ledger) && liveSensitivity(ledger!).length > 0;
    if (s.id === 'comps') return Boolean(ledger?.exit?.comps.length || ledger?.wreck?.comps.length);
    if (s.id === 'costs') return Boolean(ledger);
    return true;
  });
  const [active, setActive] = useState<string>(sections[0]?.id ?? 'damage');
  const observer = useRef<IntersectionObserver | null>(null);

  useEffect(() => {
    observer.current = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) setActive(entry.target.id);
        }
      },
      { rootMargin: '-10% 0px -70% 0px' },
    );
    for (const s of sections) {
      const el = document.getElementById(s.id);
      if (el) observer.current.observe(el);
    }
    return () => observer.current?.disconnect();
    // The section list is derived from the report and does not change after mount.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <nav
      aria-label="report sections"
      className="sticky top-0 z-10 -mx-1 flex flex-wrap gap-x-1 gap-y-1 border-b border-border bg-bg px-1 py-2"
    >
      {sections.map((s, i) => (
        <span key={s.id} className="flex items-center">
          {i > 0 && <span className="type-meta mx-1 text-faint">·</span>}
          <a
            href={`#${s.id}`}
            className={`type-meta border-b transition-colors duration-[120ms] ease-out ${
              active === s.id ? 'border-accent text-text' : 'border-transparent hover:text-text'
            }`}
          >
            {s.label}
          </a>
        </span>
      ))}
    </nav>
  );
}

// Worst four damage areas visible; the rest behind a count.
function DamageList({
  triage,
  onAnchor,
}: {
  triage: SalvageReport['triage'];
  onAnchor: (indices: number[]) => void;
}) {
  const severityRank = { heavy: 0, moderate: 1, light: 2 } as const;
  const kindRank = { structural: 0, mechanical: 1, electrical: 2, cosmetic: 3 } as const;
  const sorted = [...triage.areas].sort(
    (a, b) =>
      severityRank[a.severity] - severityRank[b.severity] || kindRank[a.kind] - kindRank[b.kind],
  );
  const lead = sorted.slice(0, 4);
  const rest = sorted.slice(4);

  const row = (area: (typeof sorted)[number], i: number) => (
    <div key={i} className="flex items-start gap-2">
      <span
        className={`mt-[7px] h-[6px] w-[6px] shrink-0 rounded-full ${
          area.kind === 'structural'
            ? 'bg-danger'
            : area.severity === 'heavy'
              ? 'bg-warn'
              : 'bg-border-strong'
        }`}
      />
      <div className="min-w-0">
        <p className="type-body max-w-[72ch]">
          <span className="font-medium capitalize">
            {area.severity} {area.kind} · {area.area}
          </span>
          <span className="text-dim"> · {area.description}</span>
        </p>
        {area.photos.length > 0 && (
          <div className="mt-1 flex gap-2">
            {area.photos.map((index) => (
              <button
                key={index}
                onClick={() => onAnchor(area.photos)}
                className="type-meta rounded-[2px] border border-border px-1.5 font-mono transition-colors duration-[120ms] ease-out hover:border-accent-dim hover:text-accent"
              >
                photo {index}
              </button>
            ))}
          </div>
        )}
      </div>
    </div>
  );

  return (
    <div className="flex flex-col gap-3">
      {lead.map(row)}
      {rest.length > 0 && (
        <details className="group">
          <summary className="type-meta cursor-pointer list-none [&::-webkit-details-marker]:hidden">
            {rest.length} lighter area{rest.length === 1 ? '' : 's'}{' '}
            <span className="text-accent group-open:hidden">expand</span>
            <span className="hidden text-accent group-open:inline">collapse</span>
          </summary>
          <div className="mt-2 flex flex-col gap-3">{rest.map((a, i) => row(a, i + 4))}</div>
        </details>
      )}
    </div>
  );
}
